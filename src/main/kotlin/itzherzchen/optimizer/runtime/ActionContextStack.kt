package itzherzchen.optimizer.runtime

import itzherzchen.optimizer.observe.Counters
import org.bukkit.Bukkit
import org.bukkit.event.block.BlockBreakEvent
import java.util.ArrayDeque
import java.util.logging.Logger

/**
 * Thread-local stack managing active ActionContext instances for Cuboid block breaks.
 *
 * Enforces fail-closed safety invariants:
 * - Stale context detection: if an unclosed context exists when a new root action begins,
 *   a prior event dispatch must have abnormally aborted before MONITOR. This trips the
 *   circuit breaker and disarms the system.
 * - Nested synthetic protection: synthetic events generated by WildTools must not create
 *   new root contexts.
 * - Off-thread protection: world mutations and synthetic block breaking must only run on the main thread.
 * - Reference hygiene: popped contexts are closed and cleared to prevent memory leaks of Player / Event references.
 */
class ActionContextStack(
    private val circuitBreaker: CircuitBreaker,
    private val counters: Counters,
    private val logger: Logger? = null,
    private val primaryThreadChecker: () -> Boolean = {
        try {
            Bukkit.isPrimaryThread()
        } catch (_: Throwable) {
            true
        }
    }
) {
    private val threadLocalStack = ThreadLocal.withInitial { ArrayDeque<ActionContext>() }

    /**
     * Pushes a new ActionContext for a verified root Cuboid action.
     * Returns true if pushed successfully, or false if rejected / disarmed due to stale context or off-thread call.
     */
    fun push(context: ActionContext): Boolean {
        if (!primaryThreadChecker()) {
            counters.circuitTrips.increment()
            logger?.severe("[Optimizer] ActionContextStack.push rejected: off-thread invocation on thread '${Thread.currentThread().name}'!")
            circuitBreaker.trip(
                ModuleType.GLOBAL,
                "Off-thread push attempted on ActionContextStack (thread: ${Thread.currentThread().name})"
            )
            return false
        }

        val stack = threadLocalStack.get()

        // Invariant: Stack must be clean before a new root action starts.
        if (!stack.isEmpty()) {
            val stale = stack.peekFirst()
            counters.validationFailures.increment()
            counters.circuitTrips.increment()
            logger?.severe(
                "[Optimizer] Stale ActionContext detected! Previous action #${stale?.actionId} was never closed before root event #${context.actionId}. Fail-closed disarm triggered."
            )
            circuitBreaker.trip(
                ModuleType.GLOBAL,
                "Stale ActionContext detected: prior action #${stale?.actionId} was not cleaned up before action #${context.actionId}"
            )
            // Clear stale state to avoid leaking memory or corrupted state
            clear()
            return false
        }

        stack.addFirst(context)
        return true
    }

    /**
     * Returns the active context on the current thread, or null if no action is in progress.
     */
    fun current(): ActionContext? {
        val stack = threadLocalStack.get()
        return stack.peekFirst()
    }

    /**
     * Pops and closes the active context on the current thread.
     * If expectedRootEvent is provided, validates that the context being closed matches the event.
     */
    fun pop(expectedRootEvent: BlockBreakEvent? = null): ActionContext? {
        val stack = threadLocalStack.get()
        if (stack.isEmpty()) return null

        val top = stack.peekFirst()
        if (expectedRootEvent != null && top.rootEvent !== expectedRootEvent) {
            counters.validationFailures.increment()
            counters.circuitTrips.increment()
            logger?.severe(
                "[Optimizer] ActionContextStack pop mismatch! Expected event $expectedRootEvent but top context had ${top.rootEvent}. Tripping circuit breaker."
            )
            circuitBreaker.trip(
                ModuleType.GLOBAL,
                "ActionContextStack pop mismatch: expected event did not match active context"
            )
            // Even on mismatch, pop and close to avoid dangling leak
            stack.pollFirst()
            top.close()
            if (stack.isEmpty()) {
                threadLocalStack.remove()
            }
            return top
        }

        val popped = stack.pollFirst()
        popped.close()
        if (stack.isEmpty()) {
            threadLocalStack.remove()
        }
        return popped
    }

    /**
     * Clears and closes all contexts on the current thread.
     */
    fun clear() {
        val stack = threadLocalStack.get()
        while (!stack.isEmpty()) {
            val ctx = stack.pollFirst()
            ctx.close()
        }
        threadLocalStack.remove()
    }

    fun depth(): Int = threadLocalStack.get().size

    fun hasActiveContext(): Boolean = !threadLocalStack.get().isEmpty()
}
